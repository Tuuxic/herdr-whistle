// Bakes every 8bit-sfx effect that video.html names into video-sfx.js, so the page plays them from file:// with no
// server and no imports.
// usage: node video-sfx-bake.mjs <path to a checkout of github.com/cportka/8bit-sfx>
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const lib = process.argv[2];
if (!lib) { console.error('usage: node video-sfx-bake.mjs <8bit-sfx dir>'); process.exit(1); }
const { renderPcm, effectNames } = await import(pathToFileURL(join(lib, 'src', 'index.js')).href);
const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, 'video.html'), 'utf8');
const known = new Set(effectNames());
const names = [...new Set(html.match(/\b[a-z]+_[a-z0-9-]+\b/g))].filter(n => known.has(n)).sort();
const data = Object.fromEntries(names.map(n => [n, Buffer.from(renderPcm(n)).toString('base64')]));
writeFileSync(join(here, 'video-sfx.js'),
  '// Generated by video-sfx-bake.mjs from 8bit-sfx (MIT, github.com/cportka/8bit-sfx).\n' +
  '// 8-bit unsigned PCM, 22050 Hz mono, base64.\nwindow.SFX_DATA=' + JSON.stringify(data, null, 0) + ';\n');
console.log(`baked ${names.length} effects:`, names.join(' '));
